#!/usr/bin/env bash
# 生成 anycon-ai/homebrew-tap 里的 Formula/anycon.rb（`brew install anycon-ai/tap/anycon`）。
#
#   packaging/homebrew-formula.sh <版本，如 0.1.0> <目录：含四个 anycon-<target>.tar.gz.sha256> > anycon.rb
#
# 发布流水线（.github/workflows/release.yml 的 homebrew job）在 GitHub Release 建好之后调用它，再把结果推到 tap 仓库。
# formula 直接装预构建的二进制（不从源码编译），四个平台各一个 url + sha256。
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "usage: $0 <version> <dir with anycon-<target>.tar.gz.sha256 files>" >&2
  exit 2
fi
version=${1#v}
dir=$2
base="https://github.com/anycon-ai/anycon/releases/download/v${version}"

sha() {
  local file="$dir/anycon-$1.tar.gz.sha256"
  local value
  value=$(cut -d ' ' -f 1 < "$file")
  if ! [[ $value =~ ^[0-9a-f]{64}$ ]]; then
    echo "bad sha256 in $file: $value" >&2
    exit 1
  fi
  printf '%s' "$value"
}

asset() {
  printf '      url "%s/anycon-%s.tar.gz"\n      sha256 "%s"' "$base" "$1" "$(sha "$1")"
}

cat <<EOF
# Generated by packaging/homebrew-formula.sh in https://github.com/anycon-ai/anycon. Do not edit by hand.
class Anycon < Formula
  desc "Run coding agents on your own machine and talk to them from anywhere"
  homepage "https://github.com/anycon-ai/anycon"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
$(asset aarch64-apple-darwin)
    end
    on_intel do
$(asset x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
$(asset aarch64-unknown-linux-gnu)
    end
    on_intel do
$(asset x86_64-unknown-linux-gnu)
    end
  end

  def install
    bin.install "anycon"
    prefix.install "THIRD-PARTY-LICENSES.txt"
    generate_completions_from_executable(bin/"anycon", "completions")
  end

  def caveats
    <<~EOS
      anycon is both the daemon and the CLI. On the machine that runs your agents:
        anycon init --hub https://hub.example.com --workspace ~/anycon
        anycon service install
      After \`brew upgrade anycon\`, run \`anycon service restart\`.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/anycon --version")
  end
end
EOF
